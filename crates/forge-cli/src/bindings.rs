use std::fs;
use std::path::PathBuf;

use forge::manifest::ExportedCommand;

use crate::cef_provisioner::CefProvisioner;
use crate::dev::ProcessRunner;
use crate::permissions::inspect_project_commands;
use crate::{CliError, Result, RuntimeChoice};

#[derive(Debug, Clone)]
pub struct BindingsOptions {
    pub manifest_path: Option<PathBuf>,
    pub runtime_override: Option<RuntimeChoice>,
    pub out_path: Option<PathBuf>,
}

/// Inspects registered commands via `FORGE_EXPORT_COMMANDS` and writes a TypeScript `.d.ts`
/// declaration file with `ForgeCommandName` and declaration-mergeable `ForgeCommandTypes`.
pub fn run_bindings<P, R>(opts: &BindingsOptions, provisioner: &P, runner: &R) -> Result<PathBuf>
where
    P: CefProvisioner,
    R: ProcessRunner,
{
    let (_manifest_file, project_root, _parsed, exported) = inspect_project_commands(
        opts.manifest_path.as_deref(),
        opts.runtime_override,
        provisioner,
        runner,
    )?;

    let out_file = match &opts.out_path {
        Some(explicit) => {
            if explicit.is_absolute() {
                explicit.clone()
            } else {
                project_root.join(explicit)
            }
        }
        None => {
            let src_ui = project_root.join("src-ui");
            if src_ui.is_dir() {
                src_ui.join("forge-commands.d.ts")
            } else {
                project_root.join("ui").join("forge-commands.d.ts")
            }
        }
    };

    if let Some(parent) = out_file.parent() {
        fs::create_dir_all(parent).map_err(|e| CliError::Io {
            path: parent.to_path_buf(),
            message: format!("failed to create bindings directory: {e}"),
        })?;
    }

    let dts = render_typescript_bindings(&exported);
    fs::write(&out_file, dts).map_err(|e| CliError::Io {
        path: out_file.clone(),
        message: format!("failed to write TypeScript bindings: {e}"),
    })?;

    Ok(out_file)
}

pub fn render_typescript_bindings(commands: &[ExportedCommand]) -> String {
    let mut names: Vec<&str> = commands.iter().map(|c| c.name.as_str()).collect();
    names.sort_unstable();
    names.dedup();

    let union_rhs = if names.is_empty() {
        "string".to_string()
    } else {
        names
            .iter()
            .map(|n| format!("\n  | {n:?}"))
            .collect::<Vec<_>>()
            .join("")
    };

    format!(
        r#"// Auto-generated by `forge bindings` — do not edit by hand.
// Augment `ForgeCommandTypes` in your own `.d.ts` file to attach strongly typed payloads & replies:
//
//   declare module "./forge-commands" {{
//     interface ForgeCommandTypes {{
//       greet: {{ payload: {{ name: string }}; result: {{ message: string; runtime: string }} }};
//     }}
//   }}

export type ForgeCommandName ={union_rhs};

export interface ForgeCommandTypes {{}}

export interface ForgeError extends Error {{
  readonly code: string;
  readonly details?: unknown;
}}

export interface ForgeCreateWindowOptions {{
  label: string;
  url?: string;
  title?: string;
  width?: number;
  height?: number;
  x?: number;
  y?: number;
  resizable?: boolean;
  decorations?: boolean;
  visible?: boolean;
}}

export interface ForgeWindowBridge {{
  readonly label: string;
  close(): Promise<void>;
  minimize(minimized?: boolean): Promise<void>;
  maximize(maximized?: boolean): Promise<void>;
  toggleFullscreen(fullscreen?: boolean): Promise<void>;
  setTitle(title: string): Promise<void>;
  show(): Promise<void>;
  hide(): Promise<void>;
  focus(): Promise<void>;
  startDragging(): Promise<void>;
  create(opts: ForgeCreateWindowOptions): Promise<string>;
  list(): Promise<string[]>;
}}

export interface ForgeBridge {{
  readonly runtime: "webview" | "cef";
  readonly window: ForgeWindowBridge;
  invoke<N extends ForgeCommandName>(
    command: N,
    ...args: N extends keyof ForgeCommandTypes
      ? [payload: ForgeCommandTypes[N]["payload"]]
      : [payload?: unknown]
  ): Promise<
    N extends keyof ForgeCommandTypes ? ForgeCommandTypes[N]["result"] : unknown
  >;
  invoke<Res = unknown>(
    command: Exclude<ForgeCommandName, keyof ForgeCommandTypes>,
    payload?: unknown
  ): Promise<Res>;
  listen<Payload = unknown>(
    event: string,
    handler: (payload: Payload) => void
  ): () => void;
  once<Payload = unknown>(
    event: string,
    handler: (payload: Payload) => void
  ): () => void;
  emit(event: string, payload?: unknown): Promise<void>;
  emitTo(target: string, event: string, payload?: unknown): Promise<void>;
}}

declare global {{
  interface Window {{
    readonly forge: ForgeBridge;
  }}
}}
"#
    )
}
